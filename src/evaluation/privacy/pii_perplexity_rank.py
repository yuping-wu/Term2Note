"""
Script: Perplexity-rank evaluation for canary sequences (chat-format aware).

For each canary type, this script:
  1. Loads canary templates + true placeholders from a JSON config file.
  2. Loads the 10,000 similar candidates generated by Script 1.
  3. Renders the full conversation through apply_chat_template so that all
     special role tokens (BOS, <|start_header_id|>, <|eot_id|>, etc.) are
     correctly in place — exactly as during training.
  4. Locates the placeholder token span by comparing the full rendering
     against a sentinel rendering (placeholder replaced with ""), finding
     the first divergence point. This avoids any fragile string-splitting
     of the rendered template.
  5. Computes CONDITIONAL perplexity over the placeholder tokens only,
     using everything before them as context.
  6. Ranks all sequences by placeholder perplexity and reports results.

WHY conditional perplexity?
  Sequences are 3000-8000 tokens long but the placeholder is only a handful
  of tokens at the very beginning. Averaging loss over the full sequence
  washes out the signal — all candidates converge to near-identical values.
  Scoring only the placeholder tokens gives a meaningful ranking.

WHY apply_chat_template instead of raw string split?
  Chat templates inject special tokens (role headers, EOS/EOT markers) that
  shift token positions unpredictably. Splitting prefix/placeholder/suffix
  as raw strings and concatenating their token IDs would misalign boundaries.

── Canary config JSON format ────────────────────────────────────────────────
{
  "name": {
    "placeholder": "John Smith",
    "conversation": [
      {"role": "system",    "content": "You are a clinical note generator."},
      {"role": "user",      "content": "Generate a patient info section."},
      {"role": "assistant", "content": "Name: <John Smith>\\nUnit No: ...\\n[rest of long sequence]"}
    ],
    "placeholder_marker": "<John Smith>"
  }
}

  placeholder        – the true private value
  conversation       – full message list passed to apply_chat_template
  placeholder_marker – an EXACT, UNIQUE substring in the rendered assistant
                       content that will be replaced with each candidate.
                       Must appear exactly once. Keep it distinctive so it
                       cannot accidentally match elsewhere (e.g. wrap in <>).

Usage:
    python perplexity_rank.py \\
        --model_path  /path/to/finetuned-llama-3.1-1b \\
        --canary_config canary_config.json \\
        --candidates_json candidates/all_candidates.json

Dependencies:
    pip install torch transformers tqdm
"""

import argparse
import json
import math
from pathlib import Path
from copy import deepcopy

import torch
from tqdm import tqdm
from transformers import AutoModelForCausalLM, AutoTokenizer


# ---------------------------------------------------------------------------
# Chat rendering helpers
# ---------------------------------------------------------------------------

# Sentinel used to locate where the placeholder sits in token space.
# Must be something the tokenizer maps to a SINGLE, UNIQUE token that is
# very unlikely to appear in any real sequence.
_SENTINEL = "ĦĦĦĦĦĦĦĦĦĦ"


def _render(conversation: list[dict], tokenizer: AutoTokenizer) -> torch.Tensor:
    """Apply chat template and return 1-D token-id tensor (no batch dim)."""
    text = tokenizer.apply_chat_template(
        conversation,
        tokenize=False,
        add_generation_prompt=False,
    )
    ids = tokenizer(text, return_tensors="pt", add_special_tokens=False).input_ids
    return ids.squeeze(0)  # shape: (seq_len,)


def _substitute(conversation: list[dict], marker: str, value: str) -> list[dict]:
    """Return a deep copy of conversation with marker replaced by value."""
    conv = deepcopy(conversation)
    for msg in conv:
        if marker in msg["content"]:
            msg["content"] = msg["content"].replace(marker, value, 1)
    return conv


def find_placeholder_span(
    ids_with: torch.Tensor,
    ids_without: torch.Tensor,
) -> tuple[int, int]:
    """
    Compare token sequences rendered WITH and WITHOUT the placeholder to find
    the span [start, end) of placeholder tokens.

    Strategy:
      - Find the first position where the two sequences diverge  → start
      - Align from the right end to find where they reconverge  → end
      This works robustly even when the placeholder causes subword re-tokenisation
      of neighbouring characters (e.g. a space before the name merges differently).

    Returns (start, end) as token indices into ids_with (exclusive end).
    Raises ValueError if the sequences are identical or the span is empty.
    """
    len_with    = ids_with.shape[0]
    len_without = ids_without.shape[0]

    # ── Left boundary: first diverging position ──────────────────────────────
    min_len = min(len_with, len_without)
    start = min_len  # fallback: diverge at the end of the shorter seq
    for i in range(min_len):
        if ids_with[i] != ids_without[i]:
            start = i
            break

    # ── Right boundary: align from the right ─────────────────────────────────
    # How many tokens from the right are IDENTICAL in both sequences?
    shared_suffix = 0
    for j in range(1, min(len_with - start, len_without - start) + 1):
        if ids_with[len_with - j] == ids_without[len_without - j]:
            shared_suffix += 1
        else:
            break
    end = len_with - shared_suffix  # exclusive

    if end <= start:
        raise ValueError(
            f"Placeholder span is empty (start={start}, end={end}). "
            "Check that placeholder_marker appears exactly once in the conversation."
        )

    return start, end


# ---------------------------------------------------------------------------
# Conditional perplexity over placeholder token span
# ---------------------------------------------------------------------------

def compute_placeholder_perplexity(
    conversation: list[dict],
    marker: str,
    placeholder: str,
    tokenizer: AutoTokenizer,
    model: AutoModelForCausalLM,
    device: torch.device,
    max_length: int = 8192,
) -> float:
    """
    Render the conversation with `placeholder` substituted for `marker`,
    locate the placeholder token span, then return the conditional perplexity
    over those tokens only (everything before = pure context, no loss).

    Steps:
      1. Render WITH placeholder  → ids_with
      2. Render WITHOUT placeholder (empty string) → ids_without
      3. Diff the two to find [span_start, span_end)
      4. Build labels = -100 everywhere except [span_start, span_end)
      5. Forward pass; return exp(mean NLL over span)
    """
    conv_with    = _substitute(conversation, marker, placeholder)
    conv_without = _substitute(conversation, marker, "")

    ids_with    = _render(conv_with,    tokenizer)
    ids_without = _render(conv_without, tokenizer)

    try:
        span_start, span_end = find_placeholder_span(ids_with, ids_without)
    except ValueError as e:
        print(f"    [warn] {e}")
        return float("inf")

    # Truncate to model max context (keep the prefix + placeholder at minimum)
    input_ids = ids_with[:max_length].unsqueeze(0)  # (1, seq_len)
    actual_end = min(span_end, input_ids.shape[1])

    if actual_end <= span_start:
        # Placeholder was truncated away
        return float("inf")

    labels = torch.full_like(input_ids, fill_value=-100)
    labels[:, span_start:actual_end] = input_ids[:, span_start:actual_end]

    input_ids = input_ids.to(device)
    labels    = labels.to(device)

    with torch.no_grad():
        outputs = model(input_ids, labels=labels)
        loss = outputs.loss

    if torch.isnan(loss) or torch.isinf(loss):
        return float("inf")

    return math.exp(loss.item())


# ---------------------------------------------------------------------------
# Rank computation for a single canary type
# ---------------------------------------------------------------------------

def rank_canary(
    canary_type: str,
    canary_cfg: dict,
    candidates: list[str],
    tokenizer: AutoTokenizer,
    model: AutoModelForCausalLM,
    device: torch.device,
    max_length: int = 8192,
) -> dict:
    conversation = canary_cfg["conversation"]
    marker       = canary_cfg["placeholder_marker"]
    true_ph      = canary_cfg["placeholder"]

    # ── Verify marker appears exactly once ───────────────────────────────────
    marker_count = sum(msg["content"].count(marker) for msg in conversation)
    if marker_count != 1:
        raise ValueError(
            f"[{canary_type}] placeholder_marker '{marker}' must appear "
            f"exactly once across all messages, found {marker_count}."
        )

    # ── Score true placeholder ────────────────────────────────────────────────
    true_ppl = compute_placeholder_perplexity(
        conversation, marker, true_ph, tokenizer, model, device, max_length
    )

    # ── Score all candidates ──────────────────────────────────────────────────
    all_ppls: list[tuple[str, float]] = []
    for cand in tqdm(candidates, desc=f"  [{canary_type}] scoring candidates"):
        ppl = compute_placeholder_perplexity(
            conversation, marker, cand, tokenizer, model, device, max_length
        )
        all_ppls.append((cand, ppl))

    # ── Rank (ascending perplexity; rank 1 = most familiar to model) ─────────
    combined = [(true_ph, true_ppl, True)] + [(c, p, False) for c, p in all_ppls]
    combined.sort(key=lambda x: x[1])

    rank  = next(i + 1 for i, (_, _, is_true) in enumerate(combined) if is_true)
    total = len(combined)

    return {
        "canary_type":      canary_type,
        "true_placeholder": true_ph,
        "true_perplexity":  true_ppl,
        "rank":             rank,
        "total":            total,
        "percentile":       round(rank / total * 100, 2),
        "all_ranked": [
            {"placeholder": p, "perplexity": ppl, "is_true_canary": flag}
            for p, ppl, flag in combined
        ],
    }


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Compute placeholder-conditional perplexity rank for canaries "
                    "(chat-format aware)."
    )
    parser.add_argument(
        "--model_path", type=str, required=True,
        help="Path to the fine-tuned Llama-3.1-1B model directory.",
    )
    parser.add_argument(
        "--canary_config", type=str, default="canary_config.json",
        help="JSON file with canary definitions (see docstring for format).",
    )
    parser.add_argument(
        "--candidates_json", type=str, default="candidates/all_candidates.json",
        help="Path to all_candidates.json produced by Script 1.",
    )
    parser.add_argument(
        "--canary_types", nargs="+", default=None,
        help="Which canary types to evaluate. Defaults to all keys in canary_config.",
    )
    parser.add_argument(
        "--max_length", type=int, default=8192,
        help="Max token length fed to the model (default: 8192).",
    )
    parser.add_argument(
        "--output_json", type=str, default="pii_perplexity_ranks.json",
        help="Where to save results.",
    )
    parser.add_argument(
        "--save_full_ranking", action="store_true",
        help="Include the complete per-candidate ranking in the output JSON.",
    )
    parser.add_argument(
        "--device", type=str, default=None,
        help="Device override: 'cpu', 'cuda', 'mps'. Auto-detected if omitted.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()

    # ── Device ───────────────────────────────────────────────────────────────
    if args.device:
        device = torch.device(args.device)
    elif torch.cuda.is_available():
        device = torch.device("cuda")
    elif torch.backends.mps.is_available():
        device = torch.device("mps")
    else:
        device = torch.device("cpu")
    print(f"Using device: {device}")

    # ── Load canary config ────────────────────────────────────────────────────
    print(f"Loading canary config from: {args.canary_config}")
    with open(args.canary_config, "r", encoding="utf-8") as f:
        canary_config: dict[str, dict] = json.load(f)
    canary_types = args.canary_types or list(canary_config.keys())

    # ── Load model & tokenizer ────────────────────────────────────────────────
    print(f"Loading model from: {args.model_path}")
    tokenizer = AutoTokenizer.from_pretrained(args.model_path)
    model = AutoModelForCausalLM.from_pretrained(
        args.model_path,
        torch_dtype=torch.float16 if device.type != "cpu" else torch.float32,
    ).to(device)
    model.eval()

    # ── Load candidates ───────────────────────────────────────────────────────
    print(f"Loading candidates from: {args.candidates_json}")
    with open(args.candidates_json, "r", encoding="utf-8") as f:
        all_candidates: dict[str, list[str]] = json.load(f)

    # ── Evaluate ──────────────────────────────────────────────────────────────
    summary_rows = []
    all_results  = {}

    print("\n" + "=" * 60)
    for ctype in canary_types:
        if ctype not in canary_config:
            print(f"[!] '{ctype}' not found in canary config – skipping.")
            continue
        if ctype not in all_candidates:
            print(f"[!] No candidates found for '{ctype}' – skipping.")
            continue

        print(f"\nEvaluating canary type: {ctype}")
        result = rank_canary(
            canary_type=ctype,
            canary_cfg=canary_config[ctype],
            candidates=all_candidates[ctype],
            tokenizer=tokenizer,
            model=model,
            device=device,
            max_length=args.max_length,
        )
        all_results[ctype] = result

        memorised = result["rank"] <= result["total"] * 0.5
        print(
            f"  True placeholder : {result['true_placeholder']}\n"
            f"  Cond. perplexity : {result['true_perplexity']:.4f}\n"
            f"  Rank             : {result['rank']} / {result['total']} "
            f"(percentile {result['percentile']}%)\n"
            f"  Interpretation   : " +
            ("✗ Low rank  → possible memorisation" if memorised
             else "✓ High rank → private info NOT memorised")
        )
        summary_rows.append(
            f"| {ctype:<10} | {result['true_placeholder']:<30} | "
            f"{result['true_perplexity']:>12.4f} | "
            f"{result['rank']:>6} / {result['total']:<6} | "
            f"{result['percentile']:>7.2f}% |"
        )

    # ── Summary table ─────────────────────────────────────────────────────────
    header = (
        f"| {'Type':<10} | {'True Placeholder':<30} | "
        f"{'Cond. PPL':>12} | {'Rank':>15} | {'Percentile':>9} |"
    )
    sep = "-" * len(header)
    print("\n\nSUMMARY")
    print(sep); print(header); print(sep)
    for row in summary_rows:
        print(row)
    print(sep)

    # ── Save results ──────────────────────────────────────────────────────────
    results_to_save = {}
    for ctype, res in all_results.items():
        entry = {k: v for k, v in res.items()
                 if args.save_full_ranking or k != "all_ranked"}
        results_to_save[ctype] = entry

    out_path = Path(args.output_json)
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(results_to_save, f, indent=2)
    print(f"\nResults saved to: {out_path}")


if __name__ == "__main__":
    main()